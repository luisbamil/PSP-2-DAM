package Equipo_Futbol;

public class Partido {
	
	protected String id1;
	protected String id2;
	protected String goles1;
	protected String goles2;
	
	public Partido(String id1, String id2, String goles1, String goles2) {
		super();
		this.id1 = id1;
		this.id2 = id2;
		this.goles1 = goles1;
		this.goles2 = goles2;
	}
	
	
}
